package com.nero.sdstorage

import android.content.ContentValues
import android.content.Context
import android.database.sqlite.SQLiteDatabase
import android.database.sqlite.SQLiteOpenHelper
import android.net.Uri

data class TrackedGameFolder(
    val packageName: String,
    val gameName: String,
    val treeUri: String,
    val autoCopy: Boolean,
    val lastScanAt: Long
)

data class GameTransferJob(
    val id: Long,
    val packageName: String,
    val sourceUri: String,
    val targetTreeUri: String,
    val fileName: String,
    val totalBytes: Long,
    val status: String,
    val progressBytes: Long,
    val speedBytesPerSecond: Long,
    val autoGenerated: Boolean
)

data class GameTransferHistory(
    val id: Long,
    val packageName: String,
    val fileName: String,
    val bytes: Long,
    val sha256: String,
    val sourceUri: String,
    val destinationUri: String,
    val status: String,
    val freedBytes: Long,
    val createdAt: Long
)

enum class SnapshotChange { NEW_FILE, CHANGED_FILE, UNCHANGED }

class SmartGameDatabase(context: Context) :
    SQLiteOpenHelper(context.applicationContext, "sd_micro_smart_game.db", null, 1) {

    override fun onCreate(db: SQLiteDatabase) {
        db.execSQL(
            """CREATE TABLE tracked_folders(
                package_name TEXT PRIMARY KEY,
                game_name TEXT NOT NULL,
                tree_uri TEXT NOT NULL,
                auto_copy INTEGER NOT NULL DEFAULT 0,
                last_scan_at INTEGER NOT NULL DEFAULT 0
            )"""
        )
        db.execSQL(
            """CREATE TABLE file_snapshots(
                package_name TEXT NOT NULL,
                document_uri TEXT NOT NULL,
                file_name TEXT NOT NULL,
                size_bytes INTEGER NOT NULL,
                modified_at INTEGER NOT NULL,
                mime_type TEXT,
                first_seen_at INTEGER NOT NULL,
                last_seen_at INTEGER NOT NULL,
                PRIMARY KEY(package_name, document_uri)
            )"""
        )
        db.execSQL(
            """CREATE TABLE transfer_jobs(
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                package_name TEXT NOT NULL,
                source_uri TEXT NOT NULL,
                target_tree_uri TEXT NOT NULL,
                file_name TEXT NOT NULL,
                total_bytes INTEGER NOT NULL,
                status TEXT NOT NULL,
                progress_bytes INTEGER NOT NULL DEFAULT 0,
                speed_bytes_per_sec INTEGER NOT NULL DEFAULT 0,
                auto_generated INTEGER NOT NULL DEFAULT 0,
                error_message TEXT,
                created_at INTEGER NOT NULL,
                updated_at INTEGER NOT NULL
            )"""
        )
        db.execSQL("CREATE INDEX transfer_jobs_status_idx ON transfer_jobs(status, created_at)")
        db.execSQL(
            """CREATE TABLE transfer_history(
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                job_id INTEGER NOT NULL UNIQUE,
                package_name TEXT NOT NULL,
                file_name TEXT NOT NULL,
                bytes_total INTEGER NOT NULL,
                sha256 TEXT NOT NULL,
                source_uri TEXT NOT NULL,
                destination_uri TEXT NOT NULL,
                status TEXT NOT NULL,
                freed_bytes INTEGER NOT NULL DEFAULT 0,
                created_at INTEGER NOT NULL
            )"""
        )
    }

    override fun onUpgrade(db: SQLiteDatabase, oldVersion: Int, newVersion: Int) = Unit

    @Synchronized
    fun saveFolder(packageName: String, gameName: String, treeUri: Uri) {
        val now = System.currentTimeMillis()
        var savedAutoCopy = 0
        writableDatabase.query("tracked_folders", arrayOf("tree_uri", "auto_copy"), "package_name=?", arrayOf(packageName), null, null, null).use { cursor ->
            if (cursor.moveToFirst() && cursor.getString(0) == treeUri.toString()) {
                savedAutoCopy = cursor.getInt(1)
            }
        }
        val values = ContentValues().apply {
            put("package_name", packageName)
            put("game_name", gameName)
            put("auto_copy", savedAutoCopy)
            put("tree_uri", treeUri.toString())
            put("last_scan_at", now)
        }
        writableDatabase.insertWithOnConflict(
            "tracked_folders", null, values, SQLiteDatabase.CONFLICT_REPLACE
        )
    }

    @Synchronized
    fun setAutoCopy(packageName: String, enabled: Boolean) {
        writableDatabase.update(
            "tracked_folders",
            ContentValues().apply { put("auto_copy", if (enabled) 1 else 0) },
            "package_name=?",
            arrayOf(packageName)
        )
    }

    @Synchronized
    fun updateFolderScanTime(packageName: String, at: Long = System.currentTimeMillis()) {
        writableDatabase.update(
            "tracked_folders",
            ContentValues().apply { put("last_scan_at", at) },
            "package_name=?",
            arrayOf(packageName)
        )
    }

    @Synchronized
    fun getFolders(): List<TrackedGameFolder> {
        val result = mutableListOf<TrackedGameFolder>()
        readableDatabase.query(
            "tracked_folders",
            arrayOf("package_name", "game_name", "tree_uri", "auto_copy", "last_scan_at"),
            null, null, null, null, "game_name ASC"
        ).use { cursor ->
            while (cursor.moveToNext()) {
                result.add(
                    TrackedGameFolder(
                        cursor.getString(0), cursor.getString(1), cursor.getString(2),
                        cursor.getInt(3) == 1, cursor.getLong(4)
                    )
                )
            }
        }
        return result
    }

    @Synchronized
    fun recordSnapshot(
        packageName: String,
        documentUri: Uri,
        name: String,
        size: Long,
        modifiedAt: Long,
        mimeType: String?
    ): SnapshotChange {
        val db = writableDatabase
        var oldSize: Long? = null
        var oldModified: Long? = null
        var oldFirstSeen: Long? = null
        db.query(
            "file_snapshots", arrayOf("size_bytes", "modified_at", "first_seen_at"),
            "package_name=? AND document_uri=?",
            arrayOf(packageName, documentUri.toString()), null, null, null
        ).use { cursor ->
            if (cursor.moveToFirst()) {
                oldSize = cursor.getLong(0)
                oldModified = cursor.getLong(1)
                oldFirstSeen = cursor.getLong(2)
            }
        }
        val now = System.currentTimeMillis()
        val change = when {
            oldSize == null -> SnapshotChange.NEW_FILE
            oldSize != size || oldModified != modifiedAt -> SnapshotChange.CHANGED_FILE
            else -> SnapshotChange.UNCHANGED
        }
        val values = ContentValues().apply {
            put("package_name", packageName)
            put("document_uri", documentUri.toString())
            put("file_name", name)
            put("size_bytes", size)
            put("modified_at", modifiedAt)
            put("mime_type", mimeType)
            put("first_seen_at", oldFirstSeen ?: now)
            put("last_seen_at", now)
        }
        db.insertWithOnConflict("file_snapshots", null, values, SQLiteDatabase.CONFLICT_REPLACE)
        return change
    }

    @Synchronized
    fun enqueueJob(
        packageName: String,
        sourceUri: Uri,
        targetTreeUri: Uri,
        fileName: String,
        totalBytes: Long,
        automatic: Boolean
    ): Long {
        val db = writableDatabase
        db.query(
            "transfer_jobs", arrayOf("id"),
            "source_uri=? AND target_tree_uri=? AND status IN ('QUEUED','RUNNING','PAUSED')",
            arrayOf(sourceUri.toString(), targetTreeUri.toString()),
            null, null, "created_at DESC", "1"
        ).use { cursor ->
            if (cursor.moveToFirst()) return cursor.getLong(0)
        }
        val now = System.currentTimeMillis()
        val values = ContentValues().apply {
            put("package_name", packageName)
            put("source_uri", sourceUri.toString())
            put("target_tree_uri", targetTreeUri.toString())
            put("file_name", fileName)
            put("total_bytes", totalBytes)
            put("status", "QUEUED")
            put("auto_generated", if (automatic) 1 else 0)
            put("created_at", now)
            put("updated_at", now)
        }
        return db.insert("transfer_jobs", null, values)
    }

    @Synchronized
    fun getNextQueuedJob(): GameTransferJob? {
        readableDatabase.query(
            "transfer_jobs",
            arrayOf("id", "package_name", "source_uri", "target_tree_uri", "file_name",
                "total_bytes", "status", "progress_bytes", "speed_bytes_per_sec", "auto_generated"),
            "status='QUEUED'", null, null, null, "created_at ASC", "1"
        ).use { cursor ->
            if (!cursor.moveToFirst()) return null
            return cursor.toJob()
        }
    }

    @Synchronized
    fun getJobs(): List<GameTransferJob> {
        val jobs = mutableListOf<GameTransferJob>()
        readableDatabase.query(
            "transfer_jobs",
            arrayOf("id", "package_name", "source_uri", "target_tree_uri", "file_name",
                "total_bytes", "status", "progress_bytes", "speed_bytes_per_sec", "auto_generated"),
            "status IN ('QUEUED','RUNNING','PAUSED','FAILED')",
            null, null, null, "created_at ASC"
        ).use { cursor -> while (cursor.moveToNext()) jobs.add(cursor.toJob()) }
        return jobs
    }

    @Synchronized
    fun updateJobStatus(id: Long, status: String, error: String? = null) {
        writableDatabase.update(
            "transfer_jobs",
            ContentValues().apply {
                put("status", status)
                put("error_message", error)
                put("updated_at", System.currentTimeMillis())
            },
            "id=?", arrayOf(id.toString())
        )
    }

    @Synchronized
    fun updateJobProgress(id: Long, bytes: Long, speed: Long) {
        writableDatabase.update(
            "transfer_jobs",
            ContentValues().apply {
                put("progress_bytes", bytes)
                put("speed_bytes_per_sec", speed)
                put("updated_at", System.currentTimeMillis())
            },
            "id=?", arrayOf(id.toString())
        )
    }

    @Synchronized
    fun finishJob(job: GameTransferJob, destinationUri: Uri, sha256: String) {
        val now = System.currentTimeMillis()
        writableDatabase.beginTransaction()
        try {
            writableDatabase.update(
                "transfer_jobs",
                ContentValues().apply {
                    put("status", "COMPLETED")
                    put("progress_bytes", job.totalBytes)
                    put("error_message", "")
                    put("updated_at", now)
                },
                "id=?", arrayOf(job.id.toString())
            )
            writableDatabase.update(
                "transfer_history",
                ContentValues().apply { put("status", "RESTORED_COPY") },
                "destination_uri=? AND status='COPIED_VERIFIED'",
                arrayOf(job.sourceUri)
            )
            writableDatabase.insertWithOnConflict(
                "transfer_history", null,
                ContentValues().apply {
                    put("job_id", job.id)
                    put("package_name", job.packageName)
                    put("file_name", job.fileName)
                    put("bytes_total", job.totalBytes)
                    put("sha256", sha256)
                    put("source_uri", job.sourceUri)
                    put("destination_uri", destinationUri.toString())
                    put("status", "COPIED_VERIFIED")
                    put("freed_bytes", 0L)
                    put("created_at", now)
                },
                SQLiteDatabase.CONFLICT_REPLACE
            )
            writableDatabase.setTransactionSuccessful()
        } finally {
            writableDatabase.endTransaction()
        }
    }

    @Synchronized
    fun failJob(id: Long, message: String, status: String = "FAILED") {
        updateJobStatus(id, status, message)
    }

    @Synchronized
    fun getHistory(): List<GameTransferHistory> {
        val values = mutableListOf<GameTransferHistory>()
        readableDatabase.query(
            "transfer_history",
            arrayOf("id", "package_name", "file_name", "bytes_total", "sha256",
                "source_uri", "destination_uri", "status", "freed_bytes", "created_at"),
            null, null, null, null, "created_at DESC", "100"
        ).use { cursor ->
            while (cursor.moveToNext()) {
                values.add(
                    GameTransferHistory(
                        cursor.getLong(0), cursor.getString(1), cursor.getString(2),
                        cursor.getLong(3), cursor.getString(4), cursor.getString(5),
                        cursor.getString(6), cursor.getString(7), cursor.getLong(8),
                        cursor.getLong(9)
                    )
                )
            }
        }
        return values
    }

    @Synchronized
    fun markSourceFreed(historyId: Long, freedBytes: Long) {
        writableDatabase.update(
            "transfer_history",
            ContentValues().apply {
                put("status", "SOURCE_DELETED_BY_USER")
                put("freed_bytes", freedBytes)
            },
            "id=?", arrayOf(historyId.toString())
        )
    }

    @Synchronized
    fun markRestored(historyId: Long) {
        writableDatabase.update(
            "transfer_history",
            ContentValues().apply { put("status", "RESTORED_COPY") },
            "id=?", arrayOf(historyId.toString())
        )
    }

    @Synchronized
    fun resetInterruptedJobs() {
        writableDatabase.update(
            "transfer_jobs",
            ContentValues().apply { put("status", "QUEUED") },
            "status='RUNNING'", null
        )
        writableDatabase.update(
            "transfer_jobs",
            ContentValues().apply { put("status", "CANCELLED") },
            "status='CANCEL_REQUESTED'", null
        )
    }

    @Synchronized
    fun cancelQueuedJob(jobId: Long) {
        updateJobStatus(jobId, "CANCELLED")
    }

    private fun android.database.Cursor.toJob() = GameTransferJob(
        getLong(0), getString(1), getString(2), getString(3), getString(4),
        getLong(5), getString(6), getLong(7), getLong(8), getInt(9) == 1
    )
}
